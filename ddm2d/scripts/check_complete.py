"""S3 completeness check of the paper runs: DONE.json, 100k steps, final.pt sha256, final checkpoint loads (model + EMA + optimizer state),
EMA model gives finite outputs, log.jsonl reaches 100k with finite losses, every logged step is present once. Writes runs/paper/STATUS.md
and runs/paper/status.json.

Usage: python scripts/check_complete.py [--threads 4]
"""
import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--threads", type=int, default=4)
    a = ap.parse_args()
    os.environ["OMP_NUM_THREADS"] = str(a.threads)
    import numpy as np
    import torch
    torch.set_num_threads(a.threads)
    from ddm2d.model import build_model
    from ddm2d.train import sha256_file

    runs = sorted(p for p in (ROOT / "runs" / "paper").iterdir() if p.is_dir() and (p / "config.json").exists())
    rows = []
    for rd in runs:
        r = {"run": rd.name, "ok": False}
        done = rd / "DONE.json"
        fin = rd / "ckpt" / "final.pt"
        r["failed_txt"] = (rd / "FAILED.txt").exists()
        if not done.exists() or not fin.exists():
            r["why"] = "missing DONE.json or ckpt/final.pt"
            rows.append(r)
            continue
        d = json.loads(done.read_text())
        r.update(steps=d["steps"], n_segments=d["n_segments"], wall_h=round(d["wall_s_total"] / 3600, 2), peak_rss_mb=d["peak_rss_mb"],
                 commit=d["git"]["commit"][:7], dirty=d["git"]["dirty_src_or_configs"])
        r["sha_ok"] = sha256_file(fin) == d["final_ckpt_sha256"]
        sd = torch.load(fin, map_location="cpu", weights_only=False)
        r["ckpt_step"] = sd["step"]
        m = build_model(sd["cfg"]["arm"])
        m.load_state_dict(sd["model"])
        e = build_model(sd["cfg"]["arm"])
        e.load_state_dict(sd["ema"])
        r["opt_state_n"] = len(sd["opt"]["state"])
        g = torch.Generator().manual_seed(0)
        x = torch.randn(256, 2, generator=g)
        with torch.no_grad():
            outs = []
            for t in (0.01, 0.5, 0.99):
                outs.append(e(t, x, torch.randn(256, 2, generator=g)) if e.stochastic else e(t, x))
        r["ema_finite"] = bool(all(torch.isfinite(o).all() for o in outs))
        log = [json.loads(l) for l in (rd / "log.jsonl").read_text().splitlines() if l.strip()]
        steps = [q["step"] for q in log]
        r["log_last_step"] = steps[-1]
        r["log_steps_unique_contiguous"] = steps == list(range(steps[0], steps[-1] + 1, 100))
        r["log_all_finite"] = bool(all(q["finite"] and np.isfinite(q["loss"]) for q in log))
        r["ema_snaps"] = len(list((rd / "ckpt").glob("ema_*.pt")))
        r["ok"] = bool(r["steps"] == 100000 and r["ckpt_step"] == 100000 and r["sha_ok"] and r["ema_finite"] and r["log_last_step"] == 100000
                       and r["log_steps_unique_contiguous"] and r["log_all_finite"] and not r["failed_txt"] and r["ema_snaps"] == 10)
        rows.append(r)
        print(r, flush=True)
    out = ROOT / "runs" / "paper"
    (out / "status.json").write_text(json.dumps(rows, indent=1) + "\n")
    cols = ["run", "ok", "steps", "ckpt_step", "sha_ok", "ema_finite", "log_last_step", "log_steps_unique_contiguous", "log_all_finite",
            "ema_snaps", "n_segments", "wall_h", "peak_rss_mb", "commit"]
    lines = ["# Paper runs: completeness (S3)", "",
             "Generated by `scripts/check_complete.py` (raw: `status.json`). A run is complete when `DONE.json` and `ckpt/final.pt` exist, the",
             "checkpoint is at step 100000 and matches the sha256 in `DONE.json`, model, EMA and optimizer state load into a fresh model, the EMA",
             "model gives finite outputs at t = 0.01, 0.5, 0.99, `log.jsonl` has every 100th step up to 100000 exactly once with finite losses,",
             "there is no `FAILED.txt`, and all 10 EMA snapshots (10k ... 100k) exist. `commit` is the code commit of the last segment.", "",
             "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    n_ok = sum(r["ok"] for r in rows)
    lines += ["", f"**{n_ok} / {len(rows)} runs complete.**", ""]
    (out / "STATUS.md").write_text("\n".join(lines))
    print(f"{n_ok}/{len(rows)} complete")


if __name__ == "__main__":
    main()
